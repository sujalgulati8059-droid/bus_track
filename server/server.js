require("dotenv").config();
const express=require("express"),http=require("http"),{Server}=require("socket.io"),cors=require("cors"),helmet=require("helmet"),morgan=require("morgan"),cookieParser=require("cookie-parser"),rateLimit=require("express-rate-limit");
const connectDB=require("./config/db"),initTracking=require("./socket/trackingSocket"),{errorHandler,notFound}=require("./middleware/errorMiddleware");
const app=express(),server=http.createServer(app),io=new Server(server,{cors:{origin:process.env.CLIENT_URL||"http://localhost:3000",methods:["GET","POST"]}});
connectDB();
app.set("io",io);
app.set("trust proxy",1);
app.use(helmet({contentSecurityPolicy:false}));
app.use(cors({origin:process.env.CLIENT_URL||"http://localhost:3000",credentials:true}));
app.use(rateLimit({windowMs:15*60*1000,max:1500,skip:req=>req.path==="/api/driver/location"}));
app.use(express.json({limit:"10kb"}));app.use(express.urlencoded({extended:true}));app.use(cookieParser());
if(process.env.NODE_ENV==="development")app.use(morgan("dev"));
app.use("/api/auth",require("./routes/authRoutes"));
app.use("/api/student",require("./routes/userRoutes"));
app.use("/api",require("./routes/busRoutes"));
app.use("/api/parking",require("./routes/parkingRoutes"));
app.use("/api/driver",require("./routes/driverRoutes"));
app.use("/api/admin/drivers",require("./routes/adminDriverRoutes"));
app.use("/api/notify",require("./routes/notifyRoutes"));
app.use("/api/bus-status",require("./routes/busStatusRoutes"));
app.get("/health",(req,res)=>res.json({ok:true}));
app.get("/",(req,res)=>res.json({message:"BusTrack Pro v2.0"}));
initTracking(io);app.set("tracking",io.trackingApi);app.use(notFound);app.use(errorHandler);
server.listen(process.env.PORT||5000,()=>console.log("Server on http://localhost:"+(process.env.PORT||5000)));