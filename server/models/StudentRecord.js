const mongoose = require("mongoose");

const studentRecordSchema = new mongoose.Schema(
  {
    uid: {
      type: String,
      required: true,
      unique: true,
      uppercase: true,
      trim: true,
    },
    name: {
      type: String,
      required: true,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model("StudentRecord", studentRecordSchema);
